-- Existing active records must not receive invented consent dates.
do $$
begin
    if (select organization_type from public.companies where id = 1)
        <> 'municipality' then
        raise exception 'Existing municipality was not classified correctly';
    end if;

    if (select newsletter_subscribed_at from public.contacts where id = 1)
        is not null then
        raise exception 'Migration invented a historical subscription date';
    end if;
end;
$$;

