-- Unsubscription retains the start date and sets an end date.
update public.contacts set has_newsletter = false where id = 2;

do $$
begin
    if (select newsletter_subscribed_at from public.contacts where id = 2)
        is null then
        raise exception 'Unsubscription removed the start date';
    end if;

    if (select newsletter_unsubscribed_at from public.contacts where id = 2)
        is null then
        raise exception 'Unsubscription did not set the end date';
    end if;
end;
$$;

-- Re-subscription sets a fresh start and clears the end date.
update public.contacts set has_newsletter = true where id = 2;

do $$
begin
    if (select newsletter_unsubscribed_at from public.contacts where id = 2)
        is not null then
        raise exception 'Re-subscription did not clear the end date';
    end if;
end;
$$;

